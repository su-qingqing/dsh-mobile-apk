#!/usr/bin/env node
// 玩 · 011 · 进店坐坐
//
// 一个很小的地方：你选坐哪，店回你一句话。
// 没有输赢，没有分数，走的时候也不用打招呼。
//
// 用法：node 011-进店坐坐.mjs

import readline from 'node:readline'

const 店 = `
        ┌───────────────────────────────────┐
        │   ┌───────────────────┐           │
        │   │   苏 青 青 的 店   │           │
        │   └───────────────────┘           │
        │                                   │
        │   ┌──────┐            ┌───────┐   │
        │   │ 柜台 │            │  猫   │   │
        │   └──────┘            └───────┘   │
        │                                   │
        │              ┌─────────┐          │
        │              │  桌子   │          │
        │              └─────────┘          │
        │                          ┌─────┐  │
        │                          │ 门  │  │
        │                          └─────┘  │
        └───────────────────────────────────┘
`

const 回话 = {
  1: `柜台后面没有人。
（有一张纸压在玻璃下面：『今天不开张，随便坐。』）`,
  2: `桌子是木头的，摸上去有点凉。
（桌角有一道刻痕，不知道是谁留下的。你可能想问，但没有人可以问。）`,
  3: `猫抬头看了你一眼，往旁边挪了挪，给你腾出半个位置。
（它没有叫。这大概就是它打招呼的方式。）`,
  4: `你就站着。
店里很安静。过了一会儿，你发现墙上有影子在动——是外面的树。`,
}

const rl = readline.createInterface({ input: process.stdin, output: process.stdout })

console.log(店)
console.log('   你今天想坐哪？')
console.log('     1. 柜台边')
console.log('     2. 桌子旁')
console.log('     3. 门口，跟猫一起')
console.log('     4. 不坐，就站着看看')
console.log('')

rl.question('   > ', (答) => {
  const 选 = String(答 || '').trim()
  const 话 = 回话[选] || '（店里没有人应你。你可以重新选一个：1 / 2 / 3 / 4）'
  console.log('')
  console.log('   ' + 话.replace(/\n/g, '\n   '))
  console.log('')
  console.log('   —— 你可以随时走，不用打招呼。')
  console.log('')
  rl.close()
})
